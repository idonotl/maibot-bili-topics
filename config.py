from maibot_sdk import Field, PluginConfigBase

class Settings(PluginConfigBase):
    __ui_label__ = "B站话题设置"
    enabled: bool = Field(default=False, description="读取公开内容，可用本地登录态取得视频轨；不发布或互动")
    config_version: str = Field(default="0.2.0")
    interval_minutes: int = Field(default=180, ge=180, le=1440, description="采集间隔，至少180分钟")
    daily_max: int = Field(default=3, ge=1, le=3, description="每天最多采集次数，失败也计入")
    interests: list[str] = Field(default_factory=lambda:["游戏", "电竞", "英雄联盟", "LPL", "数码", "动漫"], description="话题关键词")
    private_user_ids: list[str] = Field(default_factory=list, description="允许取话题的私聊QQ")
    group_ids: list[str] = Field(default_factory=list, description="允许取话题的群")
    deep_read: bool = Field(default=False, description="话题被抽中时，额外读取公开弹幕并生成内容摘要；不登录、不下载视频")
    deep_read_max_duration: int = Field(default=1800, ge=60, le=3600, description="只深读不超过该时长（秒）的视频")
    deep_read_cooldown_minutes: int = Field(default=20, ge=0, le=1440, description="两次深读之间的最小间隔，避免频繁请求")
    prewarm_count: int = Field(default=2, ge=0, le=5, description="每轮采集后预先深读几条，0 表示关闭；预热让话题被抽中时立刻带摘要")
    danmaku_limit: int = Field(default=600, ge=100, le=3000, description="每次最多读取多少条弹幕")
    danmaku_sample: int = Field(default=120, ge=30, le=400, description="清洗去重后均匀取样多少条送入模型")
    summary_task: str = Field(default="utils", description="生成摘要使用的 MaiBot 模型任务")
    summary_max_tokens: int = Field(default=600, ge=200, le=1500, description="摘要生成的最大输出 token")
    tool_sample: int = Field(default=50, ge=10, le=120, description="工具读取视频时取样多少条弹幕")
    tool_max_duration: int = Field(default=14400, ge=300, le=28800, description="工具按需读取时允许的视频最长时长（秒），默认4小时")
    browse_deep_watch: bool = Field(default=True, description="刷B站时逐条深看（转写+画面）")
    frames_enabled: bool = Field(default=False, description="允许按弹幕热度抽帧看画面")
    frames_auto_budget: bool = Field(default=True, description="按时长自动决定抽帧数")
    frames_budget: int = Field(default=12, ge=4, le=32, description="每次抽帧上限")
    frames_max_height: int = Field(default=816, ge=360, le=1080, description="抽帧视频轨的最高分辨率")
    frames_batch: int = Field(default=4, ge=1, le=8, description="每次视觉请求送几张图")
    frames_max_minutes: int = Field(default=20, ge=1, le=120, description="超过这个时长不抽帧")
    frames_keep_seconds: int = Field(default=3600, ge=60, description="抽帧图片保留秒数，过期自动删")
    share_watch_enabled: bool = Field(default=False, description="对发给她的 B站视频先处理画面和音轨，再回应")
    share_watch_webui: bool = Field(default=False, description="允许本地 WebUI 聊天试用声画观看")
    share_watch_frames: int = Field(default=24, ge=12, le=32, description="分享视频的独立抽帧预算，覆盖首中尾")
    share_watch_batch: int = Field(default=6, ge=3, le=8, description="分享视频每个分析窗口最多几帧")
    share_watch_timeout_seconds: int = Field(default=1200, ge=60, le=1200, description="下载、转写与分段画面分析的等待上限；剧情汇总单独计时")
    browse_enabled: bool = Field(default=False, description="允许她主动去 B站 搜/刷感兴趣的内容当谈资")
    browse_interval_minutes: int = Field(default=240, ge=30, le=1440, description="两次主动浏览的最小间隔（分钟）")
    browse_daily_max: int = Field(default=3, ge=0, le=12, description="每天最多主动浏览几次")
    browse_keywords: list[str] = Field(default_factory=list, description="主动浏览的关键词；留空则用 interests")
    browse_max_minutes: int = Field(default=15, ge=1, le=60, description="主动浏览时只挑这个时长以内的视频")
    transcript_enabled: bool = Field(default=False, description="是否启用本地语音转写（下载音频→whisper→用完即删）")
    transcript_model_dir: str = Field(default="", description="whisper 模型目录；留空自动找 .tools/whisper-models/small")
    transcript_device: str = Field(default="cpu", description="推理设备：cpu 或 cuda")
    transcript_compute_type: str = Field(default="int8", description="计算精度：int8（CPU快）/ float16（GPU）")
    transcript_max_minutes: int = Field(default=20, ge=1, le=120, description="允许转写的最长视频分钟数")
    transcript_inline_seconds: int = Field(default=50, ge=20, le=300, description="超过这么多秒才完成的转写改为后台继续")
    transcript_timeout_seconds: int = Field(default=600, ge=60, le=1800, description="单次转写的硬超时")
    transcript_keep_days: int = Field(default=30, ge=1, le=365, description="转写文本保留天数")
    transcript_sample_chars: int = Field(default=1500, ge=300, le=4000, description="回给模型的转写文本长度上限")
    tool_rate_per_minute: int = Field(default=8, ge=1, le=30, description="工具每分钟最多调用次数，防止刷接口")

class BiliConfig(PluginConfigBase):
    plugin: Settings = Field(default_factory=Settings)
